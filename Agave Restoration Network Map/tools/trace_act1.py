"""Trace Act 1's flat silhouettes (USA.png, State 1-9.png) into smooth SVG paths.
Output: act1-shapes.js  ->  window.ACT1_SHAPES = { usa: "<d>", states: ["<d>", ...] }
Coordinates are in the shared 2388x1668 canvas, so they line up with every PNG layer."""
import sys, json, numpy as np
from PIL import Image
from skimage import measure

root, out = sys.argv[1], sys.argv[2]

def shoelace(c):
    x, y = c[:, 1], c[:, 0]
    return 0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1)))

def trace(path, tol=0.3, min_area=3.0):
    a = np.array(Image.open(path).convert("RGBA"))[:, :, 3].astype(float)
    a = np.pad(a, 1)  # so shapes touching the edge still close
    parts = []
    for c in measure.find_contours(a, 127.5):
        if shoelace(c) < min_area:
            continue
        c = measure.approximate_polygon(c, tolerance=tol)
        pts = [(x - 1, y - 1) for y, x in c[:-1]]  # drop pad, (row,col) -> (x,y)
        n = len(pts)
        if n < 3:
            continue
        # smooth: quadratic curves through edge midpoints, vertices as control points
        mid = lambda p, q: ((p[0] + q[0]) / 2, (p[1] + q[1]) / 2)
        m0 = mid(pts[-1], pts[0])
        d = [f"M{m0[0]:.1f} {m0[1]:.1f}"]
        for i in range(n):
            p, q = pts[i], pts[(i + 1) % n]
            m = mid(p, q)
            d.append(f"Q{p[0]:.1f} {p[1]:.1f} {m[0]:.1f} {m[1]:.1f}")
        parts.append("".join(d) + "Z")
    return "".join(parts)

usa = trace(f"{root}/Background 1/USA.png", tol=0.5, min_area=6.0)
states = [trace(f"{root}/Background 1/State {i}.png") for i in range(1, 10)]
with open(out, "w") as f:
    f.write("// Generated by tools/trace_act1.py from Background 1/*.png (vector traces, 2388x1668 canvas).\n")
    f.write("window.ACT1_SHAPES = " + json.dumps({"usa": usa, "states": states}) + ";\n")
print("usa chars", len(usa), "states chars", sum(map(len, states)))
