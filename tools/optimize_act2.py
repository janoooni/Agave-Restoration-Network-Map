"""Prepare Act 2 art for the web, without changing a single drawn pixel.
- Each interactive PNG is cropped to its own drawing (+ small pad) and saved as lossless WebP.
- Full-canvas layers (Background, States, Shore) stay full size, lossless WebP.
- layers.js records every crop box in the shared 2388x1668 canvas so layers still align exactly.
Source PNGs in assets/ are never modified."""
import sys, os, json
from PIL import Image

root, outdir, manifest = sys.argv[1], sys.argv[2], sys.argv[3]
src = lambda p: os.path.join(root, "Background 2", p)
IE = "Interactive elements/"
CROP = {
    "landowners-natural": IE + "Landowners/Local Communities Natural.png",
    "landowners-hover":   IE + "Landowners/Local Communities Hover.png",
    "ngos-natural":       IE + "NGOs/NGO natural.png",
    "ngos-hover":         IE + "NGOs/NGO Hover.png",
    "private-natural":    IE + "Private & Regional Sector/Priv Sector Natural.png",
    "private-hover":      IE + "Private & Regional Sector/Priv Sector Hover.png",
    "government-natural": IE + "Government/Govt Natural.png",
    "government-hover":   IE + "Government/Govt hover.png",
    "academia-natural":   IE + "Academia & Research/Schools Natural.png",
    "academia-hover":     IE + "Academia & Research/Schools Hover.png",
    "donors-natural":     IE + "Foundation & Donors/Donor Natural.png",
    "donors-hover":       IE + "Foundation & Donors/Donor Hover.png",
    "cave":               IE + "Cave.png",
    "bat-path":           IE + "NGOs/Bats Pathway.png",
    "bats":               IE + "NGOs/Bats flying.png",
}
FULL = {"background": "Background.png", "states": "States.png", "shore": IE + "Shore.png"}
PAD = 4
os.makedirs(outdir, exist_ok=True)
out = {"W": 2388, "H": 1668, "layers": {}}
before = after = 0
for key, rel in {**FULL, **CROP}.items():
    im = Image.open(src(rel)).convert("RGBA")
    W, H = im.size
    if key in CROP:
        x0, y0, x1, y1 = im.getchannel("A").point(lambda v: 255 if v > 0 else 0).getbbox()
        x0, y0, x1, y1 = max(0, x0 - PAD), max(0, y0 - PAD), min(W, x1 + PAD), min(H, y1 + PAD)
        im = im.crop((x0, y0, x1, y1))
    else:
        x0, y0, x1, y1 = 0, 0, W, H
    path = os.path.join(outdir, key + ".webp")
    im.save(path, "WEBP", lossless=True, quality=100, method=6)
    before += os.path.getsize(src(rel)); after += os.path.getsize(path)
    out["layers"][key] = {"src": "web-assets/" + key + ".webp", "x": x0, "y": y0, "w": x1 - x0, "h": y1 - y0}
# placeholder photos: these are only stand-ins, so a high-quality JPEG is plenty
imgdir = os.path.join(os.path.dirname(root.rstrip("/")) if False else root, "Images")
out["images"] = []
for n in range(1, 8):
    p = os.path.join(root, "Images", f"placeholder-{n}.png")
    im = Image.open(p).convert("RGB")
    im.thumbnail((1800, 1800))
    dst = os.path.join(outdir, f"placeholder-{n}.jpg")
    im.save(dst, "JPEG", quality=86, optimize=True, progressive=True)
    before += os.path.getsize(p); after += os.path.getsize(dst)
    out["images"].append("web-assets/" + f"placeholder-{n}.jpg")
with open(manifest, "w") as f:
    f.write("// Generated by tools/optimize_act2.py. Crop boxes are in the shared 2388x1668 canvas.\n")
    f.write("window.LAYERS = " + json.dumps(out, indent=1) + ";\n")
print(f"{before/1e6:.1f} MB -> {after/1e6:.1f} MB")
